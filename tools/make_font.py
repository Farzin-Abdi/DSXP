# ---- the other eight faces -------------------------------------------
#
# Four faces are drawn glyph by glyph in this file. The other eight are
# cut from them here, and the note at the top of this file sets the bar
# they have to clear: a weight or a slope of a face is the same face, and
# on a six by eight body it mostly just fills in the counters. A bold and
# an italic cut of each was tried first and thrown away for exactly that
# reason - twelve entries, four designs.
#
# What is left changes the letterforms rather than the ink: feet on the
# stems, and a narrower set. Those are the two differences that survive
# at this size and that anybody would call a different typeface.
#
# Three more were tried and did not survive. An outline cut is nothing
# when the stems are one pixel wide - every pixel is already an edge, so
# the face comes out unchanged. A dot-matrix cut halves the ink of a face
# that has none to spare. And growing the x-height only thickens the
# lowercase, because there is no room above it to grow into.

def serifed(t):
    """Feet where a stem meets the baseline, and at the cap line above
    it. A slab, not a hairline: at this size a serif has to be a whole
    pixel or it is not there at all."""
    out = {}
    for ch, rows in t.items():
        n = [list(r) for r in rows]
        for x in range(6):
            col = [rows[y][x] for y in range(8)]
            if not (col[6] == '#' and col[5] == '#' and col[4] == '#'):
                continue
            if x > 0 and rows[6][x - 1] == '.': n[6][x - 1] = '#'
            if x < 5 and rows[6][x + 1] == '.': n[6][x + 1] = '#'
            if col[0] == '#' and col[1] == '#':
                if x > 0 and rows[0][x - 1] == '.': n[0][x - 1] = '#'
                if x < 5 and rows[0][x + 1] == '.': n[0][x + 1] = '#'
        out[ch] = ["".join(r) for r in n]
    return out

def narrowed(t):
    """Five columns folded into four - a set narrow enough to be a
    different face rather than the same one squeezed."""
    out = {}
    for ch, rows in t.items():
        n = []
        for r in rows:
            c = ['.'] * 6
            for x in range(5):
                if r[x] == '#': c[(x * 4) // 5] = '#'
            n.append("".join(c))
        out[ch] = n
    return out

def cut(t):
    """A break across the tall stems, and only in glyphs that have two
    of them - which is what keeps a stencil readable rather than merely
    broken."""
    out = {}
    for ch, rows in t.items():
        n = [list(r) for r in rows]
        stems = [x for x in range(6)
                 if all(rows[y][x] == '#' for y in range(2, 7))]
        if len(stems) >= 2:
            for x in stems:
                n[4][x] = '.'
        out[ch] = ["".join(r) for r in n]
    return out


def encode(rows):
    """One byte per row, bit 0 = leftmost pixel (matches gfx.c)."""
    return [sum(1 << x for x in range(6) if rows[y][x] == '#') for y in range(8)]


def preview(text):
    out = [""] * 8
    for ch in text:
        rows = G.get(ch, G['?'])
        cols = [x for x in range(6) if any(rows[y][x] == '#' for y in range(8))]
        lo, hi = (min(cols), max(cols)) if cols else (0, 2)
        for y in range(8):
            out[y] += "".join('#' if rows[y][x] == '#' else '.'
                              for x in range(lo, hi + 1)) + "."
    print("\n".join(out))


def main():
    if "--preview" in sys.argv:
        preview("Hamburgefonstiv 0123456789")
        print()
        preview("The quick brown fox; 4:22 / 128kbps")
        for nm, tbl in (("Square", G2), ("Narrow", G3), ("Round", G4)):
            print("\n--- %s ---" % nm)
            globals()["G"] = tbl
            preview("Hamburgefonstiv 0123456789")
            preview("The quick brown fox; 4:22 / 128kbps")
        return

    # punctuation comes from Sans: at this size a comma is a comma
    for c in range(32, 127):
        G5.setdefault(chr(c), G[chr(c)])

    for name, table in (("G", G), ("G2", G2), ("G3", G3), ("G4", G4), ("G5", G5)):
        missing = [chr(c) for c in range(32, 127) if chr(c) not in table]
        if missing:
            raise SystemExit("%s missing glyphs: %r" % (name, missing))

    faces = [(G, "Sans"), (G2, "Square"), (G3, "Narrow"), (G4, "Round")]
    faces += [(serifed(G),  "Roman"),   (serifed(G2), "Slab"),
              (serifed(G3), "Quill"),   (serifed(G4), "Antique")]
    faces += [(narrowed(G), "Compact"), (narrowed(G2), "Grid"),
              (cut(G2),     "Stencil"), (G5,           "Geometric")]

    path = sys.argv[1] if len(sys.argv) > 1 else "source/font_data.h"
    with open(path, "w") as f:
        f.write("/* Generated by tools/make_font.py - do not edit by hand.\n"
                " *\n"
                " * DSXP's UI typeface: 6x8 body, 1px stems, baseline on row 5,\n"
                " * descenders on rows 6-7. Bit 0 of each byte is the leftmost\n"
                " * pixel. Covers ASCII 32..126.\n"
                " */\n"
                "#ifndef DSXP_FONT_DATA_H\n#define DSXP_FONT_DATA_H\n\n"
                "#include <stdint.h>\n\n"
                "#define DSXP_FONT_FIRST 32\n"
                "#define DSXP_FONT_LAST  126\n\n"
                "#define DSXP_FONT_FACES %d\n\n" % len(faces) +
                "static const uint8_t g_dsxpFonts[DSXP_FONT_FACES]"
                "[(DSXP_FONT_LAST - DSXP_FONT_FIRST + 1) * 8] = {\n")
        for table, name in faces:
            f.write("{  /* %s */\n" % name)
            for c in range(32, 127):
                b = encode(table[chr(c)])
                label = "space" if c == 32 else chr(c)
                f.write("    %s /* %s */\n" % (",".join("0x%02X" % v for v in b) + ",", label))
            f.write("},\n")
        f.write("};\n\n#endif\n")
    print("wrote %s" % path)


if __name__ == "__main__":
    main()
